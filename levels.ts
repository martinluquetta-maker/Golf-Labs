export function parseLevel(
  id: number,
  letter: string,
  color: string,
  par: number,
  name: string,
  grid: string[],
  portalExitConfigs?: PortalExitConfig[]
): LevelData {
  return {
    id,
    letter,
    color,
    par,
    name,
    grid,
    portalExitConfigs
  };
}

