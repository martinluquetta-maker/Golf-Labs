/**
 * Get translation string by key and language
 */
export function t(key: string, lang: Language = 'es', fallback?: string): string {
  if (!key) return '';
  const currentLang = (TRANSLATIONS[lang] ? lang : 'es') as Language;
  
  // 1. Direct check in current language dictionary
  const currentDict = TRANSLATIONS[currentLang] as Record<string, string>;
  if (currentDict && currentDict[key]) {
    return currentDict[key];
  }

  // 2. Check alias map in current language
  const aliasKey = KEY_ALIASES[key];
  if (aliasKey && currentDict && currentDict[aliasKey]) {
    return currentDict[aliasKey];
  }

  // 3. Check common terms dictionary
  const commonInLang = COMMON_TERMS[currentLang];
  if (commonInLang && commonInLang[key]) {
    return commonInLang[key];
  }

  // 4. Fallback to Spanish dictionary
  const esDict = TRANSLATIONS.es as Record<string, string>;
  if (esDict && esDict[key]) {
    return esDict[key];
  }
  if (aliasKey && esDict && esDict[aliasKey]) {
    return esDict[aliasKey];
  }
  if (COMMON_TERMS.es && COMMON_TERMS.es[key]) {
    return COMMON_TERMS.es[key];
  }

  // 5. Fallback to English dictionary
  const enDict = TRANSLATIONS.en as Record<string, string>;
  if (enDict && enDict[key]) {
    return enDict[key];
  }
  if (aliasKey && enDict && enDict[aliasKey]) {
    return enDict[aliasKey];
  }
  if (COMMON_TERMS.en && COMMON_TERMS.en[key]) {
    return COMMON_TERMS.en[key];
  }

  // 6. Explicit fallback provided
  if (fallback) return fallback;

  // 7. Last resort: clean up any key with underscores instead of showing raw code
  return key.replace(/^(tab_|nav_|mp_|ach_|store_|settings_|howTo_|hud_|ranks_|lb_|set_)/, '').replace(/_/g, ' ');
}

/**
 * Load saved language from localStorage or browser preference
 */
export function getInitialLanguage(): Language {
  if (typeof window !== 'undefined') {
    try {
      const saved = localStorage.getItem('golf_lab_lang');
      if (saved && ['es', 'en', 'fr', 'de', 'pt', 'it', 'ja'].includes(saved)) {
        return saved as Language;
      }
      const browserLang = navigator.language.toLowerCase();
      if (browserLang.startsWith('es')) return 'es';
      if (browserLang.startsWith('fr')) return 'fr';
      if (browserLang.startsWith('de')) return 'de';
      if (browserLang.startsWith('pt')) return 'pt';
      if (browserLang.startsWith('it')) return 'it';
      if (browserLang.startsWith('ja')) return 'ja';
    } catch {
      // ignore
    }
  }
  return 'es';
}

export const getSavedLanguage = getInitialLanguage;

/**
 * Save selected language to localStorage
 */
export function saveLanguage(lang: Language): void {
  if (typeof window !== 'undefined') {
    try {
      localStorage.setItem('golf_lab_lang', lang);
    } catch {
      // ignore
    }
  }
}
